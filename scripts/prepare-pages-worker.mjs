// Cloudflare Pages "Advanced Mode" requires a `_worker.js` at the root of the
// published directory (here: .open-next/assets). @opennextjs/cloudflare only builds
// a Workers-style entry at .open-next/worker.js — it has no built-in Pages target
// (checked: no "pages" references anywhere in the installed package). This script
// bridges the two: `_worker.js` re-exports from `../worker.js` (a relative import, so
// `wrangler pages deploy`'s own esbuild bundling step — same mechanism `wrangler
// deploy` uses for Workers `main` — resolves it and everything it imports, all still
// living under .open-next/, into one self-contained script before upload).
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const openNextDir = path.join(root, "..", ".open-next");
const workerEntry = path.join(openNextDir, "worker.js");
const assetsDir = path.join(openNextDir, "assets");
const target = path.join(assetsDir, "_worker.js");

if (!existsSync(workerEntry)) {
  console.error(`Expected ${workerEntry} — run \`opennextjs-cloudflare build\` first.`);
  process.exit(1);
}
if (!existsSync(assetsDir)) {
  console.error(`Expected ${assetsDir} — run \`opennextjs-cloudflare build\` first.`);
  process.exit(1);
}

writeFileSync(
  target,
  `// Generated by scripts/prepare-pages-worker.mjs — do not edit by hand.\n` +
    `export * from "../worker.js";\n` +
    `export { default } from "../worker.js";\n`
);
console.log(`Wrote ${path.relative(process.cwd(), target)}`);
