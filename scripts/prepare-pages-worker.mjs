// Bridges @opennextjs/cloudflare's Workers-only build output to Cloudflare Pages
// "Advanced Mode", which has no built-in Pages target in that package (checked: no
// "pages" references anywhere in it). Two things need fixing after every
// `opennextjs-cloudflare build`:
//
// 1. Pages needs a `_worker.js` at the root of the published directory
//    (.open-next/assets) to take over all routing. `_worker.js` re-exports from
//    `../worker.js` (a relative import, so `wrangler pages deploy`'s own esbuild
//    bundling step — the same mechanism `wrangler deploy` uses for Workers `main` —
//    resolves it and everything it imports, all still living under .open-next/, into
//    one self-contained script before upload).
//
// 2. @opennextjs/cloudflare bakes `__ASSETS_RUN_WORKER_FIRST__: false` into
//    .open-next/cloudflare/init.js, read from wrangler.jsonc's `assets.run_worker_first`
//    at build time. That setting only makes sense for genuine Workers deployments,
//    where `false` means "the platform serves static assets automatically, bypassing
//    the worker" — a Workers-only mechanism. Pages configs can't declare an `assets`
//    block at all (the binding name "ASSETS" is reserved — Pages always provides one
//    itself), and Pages Advanced Mode always runs `_worker.js` for every request with
//    no platform-level static-file bypass. With the flag left at `false`, the worker's
//    own asset-resolver skips trying its (working, Pages-provided) ASSETS binding
//    entirely, so every static file (_next/static/*, images, etc.) falls through to
//    Next's own routing and 404s — confirmed by testing: files present on disk, same
//    request 404s until this flag is true, 200s once it is. Patching it here is the
//    only lever available since it can't be set via Pages config.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const openNextDir = path.join(root, "..", ".open-next");
const workerEntry = path.join(openNextDir, "worker.js");
const assetsDir = path.join(openNextDir, "assets");
const target = path.join(assetsDir, "_worker.js");
const initFile = path.join(openNextDir, "cloudflare", "init.js");

if (!existsSync(workerEntry) || !existsSync(assetsDir)) {
  console.error(`Expected ${workerEntry} and ${assetsDir} — run \`opennextjs-cloudflare build\` first.`);
  process.exit(1);
}

// --- 1. _worker.js shim ---
writeFileSync(
  target,
  `// Generated by scripts/prepare-pages-worker.mjs — do not edit by hand.\n` +
    `export * from "../worker.js";\n` +
    `export { default } from "../worker.js";\n`
);
console.log(`Wrote ${path.relative(process.cwd(), target)}`);

// --- 2. force __ASSETS_RUN_WORKER_FIRST__ to true ---
if (!existsSync(initFile)) {
  console.error(`Expected ${initFile} — @opennextjs/cloudflare's build output layout may have changed.`);
  process.exit(1);
}
const before = readFileSync(initFile, "utf8");
const needle = "__ASSETS_RUN_WORKER_FIRST__: false,";
if (!before.includes(needle)) {
  console.error(
    `Could not find "${needle}" in ${path.relative(process.cwd(), initFile)}. ` +
      `@opennextjs/cloudflare's internals likely changed — update this script's patch to match.`
  );
  process.exit(1);
}
writeFileSync(initFile, before.replace(needle, "__ASSETS_RUN_WORKER_FIRST__: true,"));
console.log(`Patched ${path.relative(process.cwd(), initFile)}: __ASSETS_RUN_WORKER_FIRST__ = true`);
